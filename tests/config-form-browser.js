async () => {
  const results=[];
  const check=(name,condition,detail)=>{results.push({name,passed:!!condition,...(detail?{detail}: {})});if(!condition)throw new Error(name);};
  const actual=document.querySelector('#config-form'),f=actual.elements;
  const change=(input,value)=>{input.value=value;input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}));};
  check('设置页直接显示可编辑资金和百分数',f.cash.value==='10000'&&f.maxEquityWeight.value==='70'&&!document.querySelector('#save-config').disabled);
  change(f.cash,'1000000');change(f.maxStockWeight,'15');change(f.maxIndustryWeight,'30');change(f.holdingMode,'positions');
  document.querySelector('#add-holding').click();
  const row=document.querySelector('.holding-card');for(const [k,v] of Object.entries({symbol:'600519',quantity:'100',cost:'1200',name:'隔离验收样例'}))change(row.querySelector('[data-field='+k+']'),v);
  check('逐行持仓控件可填写并通过浏览器校验',actual.checkValidity());
  await actual.onsubmit(new Event('submit',{cancelable:true}));
  let state=await AShareUIClient.request('get_state',{},'live');
  check('表单保存真实转换百分数和持仓代码',state.config.cash===1000000&&state.config.maxStockWeight===.15&&state.config.holdings[0].symbol==='sh600519');
  check('保存未创建研究或替换已有计划',state.latestRun===null&&state.latestPlan.id==='plan-demo');
  change(f.cash,'800000');
  const mode=document.querySelector('#data-mode');change(mode,'simulation');
  check('未保存草稿阻止跨模式混入',mode.value==='live'&&f.cash.value==='800000');
  const external={...state.config,cash:900000};await AShareUIClient.request('configure',{requestKey:crypto.randomUUID(),expectedRevision:state.revision,config:external},'live');
  await actual.onsubmit(new Event('submit',{cancelable:true}));
  state=await AShareUIClient.request('get_state',{},'live');
  check('后台新版本不会被旧草稿覆盖',state.config.cash===900000&&f.cash.value==='800000'&&document.querySelector('#config-message').textContent.includes('REVISION_CONFLICT'));
  await document.querySelector('#discard-config').onclick();
  check('明确放弃草稿后读取最新配置',f.cash.value==='900000');
  const box=document.createElement('div');document.body.append(box);
  let calls=[],mockState={mode:'live',simulation:false,revision:1,config:null,simulationDefaults:{cash:100000,maxEquityWeight:.6}};
  let unknown=false;
  const mock=AShareConfigEditor.mount(box,{request:async(op,args,mode)=>{calls.push({op,args,mode});if(op==='configure'){mockState={...mockState,revision:2,config:args.config};if(unknown)throw Object.assign(new Error('fixture unknown'),{code:'UI_UNCERTAIN'});return {configured:true};}if(op==='get_state')return mockState;return {targets:[]};}});
  mock.setState(mockState);
  const mf=box.querySelector('form'),fields=mf.elements;
  check('真实首次配置不继承模拟资金或风险',fields.cash.value===''&&fields.maxEquityWeight.value===''&&!fields.trackingEnabled.checked);
  for(const [k,v] of Object.entries({cash:1000000,maxEquityWeight:60,maxStockWeight:20,maxIndustryWeight:30,riskPerStock:1,horizonDays:30,reviewMinutes:60,holdingMode:'empty'}))change(fields[k],String(v));
  mock.setState({...mockState,revision:9,config:{cash:123}});
  check('后台刷新保留草稿及原版本',fields.cash.value==='1000000');
  fields.maxStockWeight.value='40';await mf.onsubmit(new Event('submit',{cancelable:true}));
  check('交叉风险上限错误在写入前拒绝',!calls.some(x=>x.op==='configure')&&box.querySelector('#config-message').textContent.includes('单股上限'));
  fields.maxStockWeight.value='20';unknown=true;await mf.onsubmit(new Event('submit',{cancelable:true}));
  check('未知保存结果锁定表单并提示核对',box.querySelector('#save-config').disabled&&!box.querySelector('#reconcile-config').hidden);
  await mf.onsubmit(new Event('submit',{cancelable:true}));
  check('未知结果不会盲目重复提交',calls.filter(x=>x.op==='configure').length===1&&calls.find(x=>x.op==='configure').args.expectedRevision===1);
  await box.querySelector('#reconcile-config').onclick();
  check('只读核对后解除字段锁定并显示已保存',!box.querySelector('#config-fields').disabled&&box.querySelector('#save-config').dataset.confirmed==='true'&&calls.filter(x=>x.op==='configure').length===1&&box.querySelector('#config-message').textContent.includes('已核对')&&!box.querySelector('#config-saved-next').hidden);
  box.remove();
  window.formAcceptance=results;
  return {passed:results.filter(x=>x.passed).length,total:results.length,results};
}
